"""ZionEX artwork from one set of shapes (owner's choices, 2026-11-07): the Modules mark (a 3 x 3 grid of modules,
like an ERP dashboard; the Z's diagonal in teal, its top and bottom rows solid, the two spare modules faint) and
"ZionEX" in Sora Bold ("Zion" navy, "EX" teal; shapes from branding/wordmark.json, made by make-wordmark.py).
Navy and teal, as the product has always used.

Writes the SVGs in branding/product/; then `npm run brand` (pos folder) makes every icon from them.
Everything is shapes, no fonts, so it renders the same everywhere and stays sharp at 16 px.
Run: python branding/make-artwork.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / 'product'
WM = json.loads((HERE / 'wordmark.json').read_text(encoding='utf-8'))

NAVY, NAVY_TOP, TEAL, TEAL_LIGHT, MIST = '#031E4C', '#0A3172', '#06AAAA', '#3FD0C9', '#BFEDEA'
Z = {(0, 0), (1, 0), (2, 0), (1, 1), (0, 2), (1, 2), (2, 2)}
DIAG = {(2, 0), (1, 1), (0, 2)}
DEFS = f'''<defs>
    <linearGradient id="zx-teal" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{TEAL_LIGHT}"/><stop offset="1" stop-color="{TEAL}"/></linearGradient>
    <linearGradient id="zx-tile" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{NAVY_TOP}"/><stop offset="1" stop-color="{NAVY}"/></linearGradient>
  </defs>'''


def modules(solid, diag, spare):
    """The mark on a 512 grid: modules 84 wide, 18 apart, from 112 to 400. A spare of None is left out."""
    out = []
    for r in range(3):
        for c in range(3):
            fill = diag if (c, r) in DIAG else solid if (c, r) in Z else spare
            if fill == 'outline':  # one colour: a spare module drawn as an outline
                out.append(f'<rect x="{117 + c * 102}" y="{117 + r * 102}" width="74" height="74" rx="18" fill="none" stroke="currentColor" stroke-width="10"/>')
            elif fill:
                out.append(f'<rect x="{112 + c * 102}" y="{112 + r * 102}" width="84" height="84" rx="22" fill="{fill}"/>')
    return ''.join(out)


def wordmark(zion, ex, x, y, cap):
    """ "ZionEX" with its caps `cap` high, from (x, y) at the cap top."""
    s = cap / WM['cap_height']
    return (f'<g transform="translate({x} {y}) scale({s:.5f})">'
            f'<path d="{WM["Zion"]}" fill="{zion}"/><path d="{WM["EX"]}" fill="{ex}"/></g>')


def lockup(cells, zion, ex, label):
    # The mark (96 high), a gap of a third of the mark, then the name with its caps 84 high, both centred on y = 80.
    cap, gap = 84, 30
    width = round(96 + gap + WM['width'] * cap / WM['cap_height']) + 4
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 160" role="img" aria-label="ZionEX">
  <!-- {label} Generated by branding/make-artwork.py: edit there, not here. -->
  {DEFS}
  <g transform="translate(-37.33 -5.33) scale(0.33333)">{cells}</g>
  {wordmark(zion, ex, 96 + gap, 80 - cap / 2, cap)}
</svg>
'''


files = {
    # App icon, favicon, installers, desktop apps: the modules on a navy tile.
    'mark.svg': f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="ZionEX">
  <!-- ZionEX mark: a grid of modules (the business), the Z's diagonal in teal. Generated by branding/make-artwork.py. -->
  {DEFS}
  <rect x="8" y="8" width="496" height="496" rx="120" fill="url(#zx-tile)"/>
  {modules('#FFFFFF', 'url(#zx-teal)', 'rgba(255,255,255,.16)')}
</svg>
''',
    # Without the tile, for light backgrounds.
    'mark-flat.svg': f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="96 96 320 320" role="img" aria-label="ZionEX">
  <!-- ZionEX mark without a tile, for light backgrounds. Generated by branding/make-artwork.py. -->
  {DEFS}
  {modules(NAVY, 'url(#zx-teal)', MIST)}
</svg>
''',
    # One colour: receipts, stamps, embroidery. The spare modules as outlines (no tints in one colour).
    'mark-mono.svg': f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="96 96 320 320" role="img" aria-label="ZionEX">
  <!-- ZionEX mark in one colour (currentColor). Generated by branding/make-artwork.py. -->
  {modules('currentColor', 'currentColor', 'outline')}
</svg>
''',
    'logo.svg': lockup(modules(NAVY, 'url(#zx-teal)', MIST), NAVY, TEAL, 'ZionEX logo for light backgrounds.'),
    'logo-dark.svg': lockup(modules('#FFFFFF', 'url(#zx-teal)', 'rgba(255,255,255,.18)'), '#FFFFFF', TEAL_LIGHT, 'ZionEX logo for dark backgrounds.'),
    'logo-mono.svg': lockup(modules('currentColor', 'currentColor', 'outline'), 'currentColor', 'currentColor', 'ZionEX logo in one colour (currentColor): receipts and print.'),
}
for name, svg in files.items():
    (OUT / name).write_text(svg, encoding='utf-8', newline='\n')
    print('wrote', name)
